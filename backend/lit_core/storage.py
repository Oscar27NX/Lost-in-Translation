from __future__ import annotations

import json

from .fixtures import REPO_ROOT
from .schemas import LineStatus, ModelConfig, TranslationSession

DATA_DIR = REPO_ROOT / "data"
SESSIONS_DIR = DATA_DIR / "sessions"
CONFIG_PATH = DATA_DIR / "model_config.json"


def _ensure_dirs() -> None:
    SESSIONS_DIR.mkdir(parents=True, exist_ok=True)


def save_session(session: TranslationSession) -> None:
    _ensure_dirs()
    path = SESSIONS_DIR / f"{session.session_id}.json"
    path.write_text(session.model_dump_json(indent=2), encoding="utf-8")


def load_session(session_id: str) -> TranslationSession | None:
    _ensure_dirs()
    path = SESSIONS_DIR / f"{session_id}.json"
    if not path.exists():
        return None
    return TranslationSession.model_validate_json(path.read_text(encoding="utf-8"))


def list_sessions() -> list[TranslationSession]:
    _ensure_dirs()
    sessions: list[TranslationSession] = []
    for path in sorted(SESSIONS_DIR.glob("*.json"), key=lambda p: p.stat().st_mtime, reverse=True):
        try:
            sessions.append(TranslationSession.model_validate_json(path.read_text(encoding="utf-8")))
        except Exception:
            continue
    return sessions


def load_model_config() -> ModelConfig:
    _ensure_dirs()
    if CONFIG_PATH.exists():
        try:
            return ModelConfig.model_validate_json(CONFIG_PATH.read_text(encoding="utf-8"))
        except Exception:
            pass
    return ModelConfig()


def save_model_config(config: ModelConfig) -> None:
    _ensure_dirs()
    CONFIG_PATH.write_text(config.model_dump_json(indent=2), encoding="utf-8")


def export_session_latex(session: TranslationSession, include_provenance: bool = True) -> str:
    out: list[str] = [
        r"% Generated by Lost In Translation (Lean 4 InfoTree -> Faithful LaTeX)",
        rf"% Theorem: {session.infotree.theorem_name} | Model: {session.model_id}",
        r"\begin{theorem}",
        f"  ${session.infotree.statement_latex}$",
        r"\end{theorem}",
        r"\begin{proof}",
    ]
    for line in session.lines:
        if include_provenance:
            flags_note = f" | flags={len([f for f in line.flags if not f.resolved])}" if line.flags else ""
            out.append(
                f"  % [LIT Step {line.line_number} <- Lean L{line.lean_span.start_line}-L{line.lean_span.end_line} "
                f"| status={line.status.value} | conf={line.derivation.confidence:.2f}{flags_note}]"
            )
            out.append(f"  % Justification: {line.derivation.justification}")
        indent = "  " * (line.indent_level + 1)
        out.append(f"{indent}$${line.latex}$$")
    out.append(r"\end{proof}")
    return "\n".join(out) + "\n"


def export_hitl_jsonl(session: TranslationSession) -> str:
    """
    Export Human-in-the-Loop annotations into SFT + DPO JSONL records ready
    for `training/train_lora.py`.
    - Verified or Human-Edited lines emit SFT supervised examples.
    - Human-Edited lines where `latex != original_latex` (or Flagged + Regenerated/Edited)
      also emit DPO preference pairs (`chosen` vs `rejected` with error taxonomy).
    """
    node_map = {n.node_id: n for n in session.infotree.nodes}
    records: list[dict] = []

    for line in session.lines:
        nodes = [node_map[nid].model_dump() for nid in line.infotree_node_ids if nid in node_map]
        lean_slice = "\n".join(
            session.infotree.source_code.splitlines()[line.lean_span.start_line - 1 : line.lean_span.end_line]
        )
        prompt_payload = {
            "theorem": session.infotree.theorem_name,
            "statement_lean": session.infotree.statement_lean,
            "lean_span": line.lean_span.model_dump(),
            "lean_slice": lean_slice,
            "infotree_nodes": nodes,
        }

        if line.status in (LineStatus.VERIFIED, LineStatus.EDITED):
            records.append(
                {
                    "record_type": "sft",
                    "session_id": session.session_id,
                    "line_id": line.line_id,
                    "status": line.status.value,
                    "input": prompt_payload,
                    "output": {
                        "latex": line.latex,
                        "procedure": line.derivation.procedure,
                        "justification": line.derivation.justification,
                        "opaque_automation": line.derivation.opaque_automation,
                    },
                }
            )

        if line.latex.strip() != line.original_latex.strip():
            flag_cats = sorted({c.value for f in line.flags for c in f.categories})
            flag_notes = [f.comment for f in line.flags if f.comment]
            records.append(
                {
                    "record_type": "dpo_preference",
                    "session_id": session.session_id,
                    "line_id": line.line_id,
                    "input": prompt_payload,
                    "chosen": line.latex,
                    "rejected": line.original_latex,
                    "flag_categories": flag_cats,
                    "reviewer_notes": flag_notes,
                }
            )
        elif line.status == LineStatus.FLAGGED and line.flags:
            records.append(
                {
                    "record_type": "adversarial_flag_negative",
                    "session_id": session.session_id,
                    "line_id": line.line_id,
                    "input": prompt_payload,
                    "rejected": line.latex,
                    "flag_categories": sorted({c.value for f in line.flags for c in f.categories}),
                    "reviewer_notes": [f.comment for f in line.flags if f.comment],
                }
            )

    return "\n".join(json.dumps(r, ensure_ascii=False) for r in records) + ("\n" if records else "")
